/** A request the Play gate refused. Thrown before any token is minted or request sent. */
export class PlayWriteDenied extends StoreWriteDenied {
  constructor(method: string, target: string, reason: DenyReason) {
    super(
      "google-play",
      method,
      target,
      reason,
      `Google Play write gate refused ${method} ${target}: ${reason}`,
    );
    this.name = "PlayWriteDenied";
  }
}

// ── What a gated request carries ─────────────────────────────────────────────────────────────

/**
 * The gate's view of one Play request (the engine's `body`): its query parameters, and either a
 * JSON body or an upload's descriptor. The client builds it from what it is about to send.
 */
export interface PlayGateRequest {
  query?: Record<string, string>;
  json?: unknown;
  upload?: UploadDescriptor;
}

/**
 * What a handler asserts about an edit it commits, or a track it patches (`ctx.resourceState`).
 * A commit carries no body, so this is the only way the gate learns what the edit holds.
 */
export const PLAY_EDIT_SCOPE = {
  /** Listing text, images, closed tracks, testers, release notes and releases on testing tracks
   *  only: no production track and no release-status change. Plain. */
  testing: "play-edit:testing",
  /** One of P5-03's rollout controls (`connectors/play/controls.ts`), with their own
   *  confirmations. Plain here (see the file comment). */
  rolloutControl: "play-edit:rollout-control",
  /** Production, or a release-status change: typed. Also what a missing scope means. */
  production: "play-edit:production",
} as const;

/** A query parameter's allowed values. */
interface QueryShape {
  values?: readonly string[];
  pattern?: RegExp;
}

export interface PlayRule extends GateRule {
  /** What the request carries besides its query. */
  carries: "none" | "json" | "upload";
  /** The query parameters it may carry; any other is refused. */
  query?: Readonly<Record<string, QueryShape>>;
  /** Query parameters it must carry. */
  requiredQuery?: readonly string[];
  /** `json`: the body's shape (`match/json.ts`). */
  json?: Readonly<Record<string, JsonShape>>;
  /** `upload`: the accepted media types and the byte cap (`match/multipart.ts`). */
  contentTypes?: readonly string[];
  maxBytes?: number;
  /** Value checks after the shape, with the request path (its `{placeholders}` filled). */
  check?: (
    req: PlayGateRequest,
    path: string,
    ctx: GateContext,
  ) => DenyReason | null;
}


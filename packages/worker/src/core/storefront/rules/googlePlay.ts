/** The last segment of a request path (the gate sees paths unencoded). */
function lastSegment(path: string): string {
  return path.slice(path.lastIndexOf("/") + 1);
}

/** A segment of a request path by its index in the template's segments. */
function segmentAt(path: string, index: number): string {
  return path.split("/")[index] ?? "";
}

function isHttpsUrl(v: unknown, hosts?: readonly string[]): boolean {
  if (typeof v !== "string" || v.length > 2048) return false;
  try {
    const u = new URL(v);
    return (
      u.protocol === "https:" &&
      u.username === "" &&
      u.password === "" &&
      (!hosts || hosts.includes(u.hostname))
    );
  } catch {
    return false;
  }
}

const YOUTUBE = ["www.youtube.com", "youtube.com", "youtu.be", "m.youtube.com"];

/** Typed for a production touch, unless the handler asserted a plain scope. */
function editScopeConfirm(ctx: GateContext): DenyReason | null {
  if (
    ctx.resourceState === PLAY_EDIT_SCOPE.testing ||
    ctx.resourceState === PLAY_EDIT_SCOPE.rolloutControl
  )
    return null;
  return checkConfirm("typed", ctx);
}


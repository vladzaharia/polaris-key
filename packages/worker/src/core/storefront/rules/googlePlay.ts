// ── Matching ─────────────────────────────────────────────────────────────────────────────────

/** The Play matcher: query, then the body by what the rule carries, then the rule's check. */
export function matchPlay(
  rule: PlayRule,
  path: string,
  body: unknown,
  ctx: GateContext,
): DenyReason | null {
  if (!isPlainObject(body) || !onlyKeys(body, ["query", "json", "upload"]))
    return "invalid_body";
  const req = body as PlayGateRequest;
  const query = req.query ?? {};
  if (!isPlainObject(query)) return "invalid_body";
  for (const [k, v] of Object.entries(query)) {
    if (!rule.query || !Object.hasOwn(rule.query, k))
      return "attribute_not_allowed";
    const shape = rule.query[k]!;
    if (typeof v !== "string" || v.length > 512) return "invalid_body";
    if (shape.values && !shape.values.includes(v)) return "value_not_allowed";
    if (shape.pattern && !shape.pattern.test(v)) return "value_not_allowed";
  }
  for (const k of rule.requiredQuery ?? [])
    if (!Object.hasOwn(query, k)) return "invalid_body";
  switch (rule.carries) {
    case "none":
      if (req.json !== undefined || req.upload !== undefined)
        return "invalid_body";
      break;
    case "json": {
      if (req.upload !== undefined) return "invalid_body";
      // The shape only: the rule's own check runs below, with the whole request.
      const r = matchJson(
        {
          method: rule.method,
          path: rule.path,
          confirm: "plain",
          why: rule.why,
          body: rule.json ?? {},
        },
        path,
        req.json,
        ctx,
      );
      if (r) return r;
      break;
    }
    case "upload": {
      if (req.json !== undefined) return "invalid_body";
      const r = matchUpload(
        {
          method: rule.method,
          path: rule.path,
          confirm: "plain",
          why: rule.why,
          contentTypes: rule.contentTypes ?? [],
          maxBytes: rule.maxBytes ?? 0,
        },
        path,
        req.upload,
        ctx,
      );
      if (r) return r;
      break;
    }
  }
  return rule.check ? rule.check(req, path, ctx) : null;
}

/** The Permissions API (`users`, `grants`): refused for every method, reads included. */
function isPermissionsPath(path: string): boolean {
  return /^\/androidpublisher\/v3\/developers(\/|$)/i.test(path);
}

/** One request-path segment: a package name, an edit id, a language, a track id (`wear:beta`). */
const PLAY_PLACEHOLDER = "[A-Za-z0-9][A-Za-z0-9 ._:+=-]{0,199}";
const PLAY_SEGMENT = new RegExp(`^${PLAY_PLACEHOLDER}$`);

/** The Play rule set, as the store-agnostic engine takes it. */
export const GOOGLE_PLAY_GATE: GateRuleSet<PlayRule> = {
  store: "google-play",
  specPin: PLAY_SPEC_PIN,
  allow: PLAY_WRITE_ALLOW,
  denied: PLAY_WRITE_DENIED,
  denyReasons: PLAY_DENY_REASONS,
  validPath: (path) =>
    path.startsWith("/androidpublisher/v3/") &&
    path
      .slice("/androidpublisher/v3/".length)
      .split("/")
      .every((s) => PLAY_SEGMENT.test(s)),
  forbidden: isPermissionsPath,
  placeholder: PLAY_PLACEHOLDER,
  match: matchPlay,
  deny: (method, target, reason) => new PlayWriteDenied(method, target, reason),
};

/** The compiled Play gate: what `GoogleApiClient` and the Play adapter consult. */
export const GOOGLE_PLAY_COMPILED_GATE = compileGate(GOOGLE_PLAY_GATE);

/**
 * Admit or refuse one Android Publisher request (the full path, `/androidpublisher/v3/…`, its
 * segments unencoded). Throws `PlayWriteDenied`; returns the matched rule for a write (null for an
 * admitted read). Pure: no I/O, no token.
 */
export function checkPlayRequest(
  method: string,
  path: string,
  req: PlayGateRequest | undefined,
  ctx: GateContext = {},
): PlayRule | null {
  return GOOGLE_PLAY_COMPILED_GATE.check(method, path, req, ctx);
}

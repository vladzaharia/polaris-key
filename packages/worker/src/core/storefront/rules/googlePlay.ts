/**
 * The Google Play write gate's rule table (A-18e; notes/S-15 §4.1, §6.2, owner decisions 2, 4 and 6
 * of 2026-10-04), on the store-agnostic engine (`../gate.ts`).
 *
 * The Worker holds a Play service account (A-16's `google-play.service-account`, or a product's own
 * `google-service-account`). Its one OAuth scope, `androidpublisher`, reaches every method of the
 * API; the Play Console permissions (S-15 decision 4: "Manage store presence", "Manage testing
 * tracks and edit tester lists" and the release permissions, never Admin, no "Manage policy
 * declarations") are the vendor-side control, and "Manage store presence" also covers PRICES. So
 * THIS TABLE is what keeps a console session (or a compromised Worker path) to the approved surface:
 *
 *   - `GoogleApiClient` (`connectors/play/client.ts`) calls `checkPlayRequest` **before its token
 *     thunk runs** for every Android Publisher request a gated client sends. A refusal throws
 *     `PlayWriteDenied`: no token is minted and nothing is sent.
 *   - A write passes only when a `PLAY_WRITE_ALLOW` rule matches its method and its path template
 *     (the discovery document's `flatPath`) exactly, AND its query parameters, AND its body: a
 *     JSON body's every key (`json`), an upload's content type and size (`upload`, from the blob
 *     store's record; the bytes are never seen here), or no body at all (`none`).
 *   - No rule allows a `DELETE` (owner rule: never delete; the engine refuses one at compile time),
 *     a user or grant, a signing key or app recovery, a refund or any other payment action, or a
 *     binary upload (CI only, decision 2).
 *   - Reads are free, except the Permissions API (`/developers/…`), refused for every method.
 *   - TYPED CONFIRMATION (S-15 §6.4): an `edits.commit` whose edit touches production or changes a
 *     release status, a production release `completed` or at a `userFraction` of 1.0, and any
 *     one-time product price after the initial one. The handler compares what the operator typed
 *     (Play's default-language title, `confirm.ts`) and only then asserts `typedConfirmation`.
 *     Since a commit has no body, the handler tells the gate what its edit holds through
 *     `resourceState` (`PLAY_EDIT_SCOPE`): a missing scope is treated as the most dangerous one.
 *     P5-03's rollout controls (fraction, halt, resume, complete, priority, and the vitals
 *     auto-halt) keep their own confirmations (`confirmRollback`) and assert
 *     `PLAY_EDIT_SCOPE.rolloutControl`, the one scope that is not typed here; making the
 *     production `complete` typed too is a proposed follow-up, not this table's change.
 *
 * `test/storefront/conformance.test.ts` classifies EVERY write method of the pinned discovery
 * document (`test/fixtures/play/discovery-writes.json`, generated by `scripts/play-spec-writes.mjs`
 * from the revision and canonical SHA-256 in `PLAY_SPEC_PIN`) as allowed here or denied, with a
 * reason, in `googlePlayDenied.ts`. A revision bump fails CI until each new write is classified. A
 * change to `PLAY_WRITE_ALLOW` is a THREAT-MODEL §9 review trigger.
 *
 * Messages never carry a body value: a `PlayWriteDenied` names the method, the template (or the
 * path when nothing matched) and a fixed reason.
 */


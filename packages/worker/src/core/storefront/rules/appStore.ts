/**
 * The App Store Connect write gate's rule table (A-17a; notes/S-14 §7.5, owner decision 1 of
 * 2026-10-04), moved unchanged by A-18a into the store-agnostic gate (`../gate.ts`, the engine;
 * `../match/jsonapi.ts`, the body matcher). This file is the first adapter's rule set.
 *
 * The Worker holds the team's **Admin** App Store Connect key (`PLATFORM_ASC_API_KEY`, A-16). An
 * Admin key can invite users, create and revoke certificates and delete apps' identifiers; the
 * owner declined a narrower App Manager key, so THIS TABLE is the only barrier between a console
 * session (or a compromised Worker path) and those powers. It is deny-by-default:
 *
 *   - `AscClient.request` calls `checkAscRequest` **before the token thunk runs**. A request this
 *     module refuses throws `AscWriteDenied`: no token is minted and nothing is sent.
 *   - A write (`POST`, `PATCH`, `PUT`, `DELETE`) passes only when an `ASC_WRITE_ALLOW` rule matches
 *     its method and path template exactly AND its JSON:API body: the resource type, every
 *     attribute key, every relationship name and the type of every identifier it names, the
 *     `included` resource types, and the rule's own value checks. Anything else is refused.
 *   - No rule allows a `DELETE` (owner decision: never delete anything), and none touches users,
 *     certificates, devices or profiles.
 *   - Reads are free except personal data and team membership (`/v1/users*`,
 *     `/v1/userInvitations*`), refused outright.
 *   - Release, submit-for-review and price changes need a **typed confirmation**: the handler
 *     compares what the operator typed (the app's name) and only then passes
 *     `{ typedConfirmation: true }`. A rule with `confirm: "typed"` refuses a request without it,
 *     so a handler that forgets the check cannot send the write.
 *
 * `test/ascWriteGate.test.ts` classifies EVERY write operation of a pinned copy of Apple's OpenAPI
 * document (`test/fixtures/asc/openapi-writes.json`, generated by `scripts/asc-spec-writes.mjs`
 * from the spec whose SHA-256 is `ASC_SPEC_PIN`) as allowed here or denied, with a reason, in
 * `appStoreDenied.ts`. An unclassified operation, or an allow rule the spec does not have, fails
 * CI; so does a spec bump until each new write is classified. A change to `ASC_WRITE_ALLOW` is a
 * THREAT-MODEL §9 review trigger (any `core/storefront/rules/*` table).
 *
 * Messages never carry a body value: an `AscWriteDenied` names the method, the path template (or
 * the path when nothing matched) and a fixed reason.
 */


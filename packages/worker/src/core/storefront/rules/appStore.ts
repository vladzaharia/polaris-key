/** A request the App Store Connect gate refused. Thrown before any token is minted or request sent. */
export class AscWriteDenied extends StoreWriteDenied {
  constructor(method: string, target: string, reason: AscDenyReason) {
    super(
      "app-store",
      method,
      target,
      reason,
      `App Store Connect write gate refused ${method} ${target}: ${reason}`,
    );
    this.name = "AscWriteDenied";
  }
}


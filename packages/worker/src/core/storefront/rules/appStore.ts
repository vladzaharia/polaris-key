// ── Matching ─────────────────────────────────────────────────────────────────────────────────

/** Personal data and team membership: refused for every method, reads included. */
function isPersonalData(path: string): boolean {
  // Case-insensitive: a `/v1/Users` spelling is refused too, whatever Apple would answer.
  return /^\/v1\/(users|userinvitations)(\/|$)/i.test(path);
}

/** The App Store's rule set, as the store-agnostic engine takes it. */
export const APP_STORE_GATE: GateRuleSet<AscAllowRule> = {
  store: "app-store",
  specPin: ASC_SPEC_PIN,
  allow: ASC_WRITE_ALLOW,
  denied: ASC_WRITE_DENIED,
  denyReasons: ASC_DENY_REASONS,
  validPath: (path) =>
    /^\/v[12]\//.test(path) &&
    path
      .slice(4)
      .split("/")
      .every((s) => PATH_SEGMENT.test(s)),
  forbidden: isPersonalData,
  match: matchJsonApi,
  deny: (method, target, reason) => new AscWriteDenied(method, target, reason),
};

const GATE = compileGate(APP_STORE_GATE);

/** The allow rule for one method and request path, or null. */
export function findAllowRule(
  method: string,
  path: string,
): AscAllowRule | null {
  return GATE.find(method, path);
}

/**
 * Admit or refuse one App Store Connect request. Throws `AscWriteDenied`; returns the matched
 * rule for a write (null for an admitted read). Pure: no I/O, no token.
 */
export function checkAscRequest(
  method: string,
  path: string,
  body: unknown,
  ctx: AscGateContext = {},
): AscAllowRule | null {
  return GATE.check(method, path, body, ctx);
}

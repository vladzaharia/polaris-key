/**
 * The App Store Connect write gate (A-17a; notes/S-14 §7.5, owner decision 1 of 2026-10-04).
 *
 * The Worker holds the team's **Admin** App Store Connect key (`PLATFORM_ASC_API_KEY`, A-16). An
 * Admin key can invite users, create and revoke certificates and delete apps' identifiers; the
 * owner declined a narrower App Manager key, so THIS TABLE is the only barrier between a console
 * session (or a compromised Worker path) and those powers. It is deny-by-default:
 *
 *   - `AscClient.request` calls `checkAscRequest` **before the token thunk runs**. A request this
 *     module refuses throws `AscWriteDenied`: no token is minted and nothing is sent.
 *   - A write (`POST`, `PATCH`, `PUT`, `DELETE`) passes only when an `ASC_WRITE_ALLOW` rule matches
 *     its method and path template exactly AND its JSON:API body: the resource type, every
 *     attribute key, every relationship name and the type of every identifier it names, the
 *     `included` resource types, and the rule's own value checks. Anything else is refused.
 *   - No rule allows a `DELETE` (owner decision: never delete anything), and none touches users,
 *     certificates, devices or profiles.
 *   - Reads are free except personal data and team membership (`/v1/users*`,
 *     `/v1/userInvitations*`), refused outright.
 *   - Release, submit-for-review and price changes need a **typed confirmation**: the handler
 *     compares what the operator typed (the app's name) and only then passes
 *     `{ typedConfirmation: true }`. A rule with `confirm: "typed"` refuses a request without it,
 *     so a handler that forgets the check cannot send the write.
 *
 * `test/ascWriteGate.test.ts` classifies EVERY write operation of a pinned copy of Apple's OpenAPI
 * document (`test/fixtures/asc/openapi-writes.json`, generated by `scripts/asc-spec-writes.mjs`
 * from the spec whose SHA-256 is `ASC_SPEC_PIN`) as allowed here or denied, with a reason, in
 * `writeGateDenied.ts`. An unclassified operation, or an allow rule the spec does not have, fails
 * CI; so does a spec bump until each new write is classified. A change to `ASC_WRITE_ALLOW` is a
 * THREAT-MODEL §9 review trigger.
 *
 * Messages never carry a body value: an `AscWriteDenied` names the method, the path template (or
 * the path when nothing matched) and a fixed reason.
 */

/** The App Store Connect OpenAPI document the gate is classified against (S-14 §13). */
export const ASC_SPEC_PIN = {
  title: "App Store Connect API",
  version: "4.5",
  sha256: "1e8ef250d6a41bab0f5670b669abf3f06298ef129c8455ba258149fda86927b2",
} as const;

export type AscMethod = "GET" | "POST" | "PATCH" | "PUT" | "DELETE";

/**
 * What a handler asserts about one write, beyond the body.
 *
 *   - `typedConfirmation`: the operator typed the confirmation phrase (the app's name) and the
 *     handler compared it with Apple's own value before calling.
 *   - `initial`: the handler's natural-key pre-read found no existing object of this kind (the
 *     first price schedule, the first availability), so the write sets rather than changes.
 *   - `hookOrigin`: the Worker's own public origin (`https://key.plrs.im`), from the request the
 *     handler is serving. A callback URL (the webhook, the App Store Server Notifications URL) is
 *     admitted only on this exact origin; without it, every callback URL is refused.
 */
export interface AscGateContext {
  typedConfirmation?: boolean;
  initial?: boolean;
  hookOrigin?: string;
}

/**
 * How a rule is confirmed.
 *
 *   - `plain`             the console's ordinary confirm (no assertion needed here);
 *   - `typed`             `typedConfirmation` required;
 *   - `initial`           `initial` required: the rule is a first-time set only;
 *   - `typed-or-initial`  a first-time set, or a change confirmed by typing (prices).
 */
export type AscConfirm = "plain" | "typed" | "initial" | "typed-or-initial";

/** A rule's extra check on the request's `data` object: a refusal reason, or null. */
type DataCheck = (
  data: JsonApiData,
  ctx: AscGateContext,
) => AscDenyReason | null;

export interface AscAllowRule {
  method: Exclude<AscMethod, "GET" | "DELETE">;
  /** Apple's path template, exactly as the spec spells it (`/v1/betaGroups/{id}`). */
  path: string;
  /** The JSON:API resource type of `data` (or of each identifier, for a linkage path). */
  type: string;
  /** Attribute keys the body may carry. */
  attributes: readonly string[];
  /** Relationship name → the identifier type it must name. */
  relationships: Readonly<Record<string, string>>;
  /** Resource types an `included` array may carry (inline creates: prices, territories). */
  included?: readonly string[];
  confirm: AscConfirm;
  check?: DataCheck;
  /** Why the operation is on the approved surface (S-14 §7.5), for the reviewer. */
  why: string;
}

/** The fixed refusal reasons (never a body value). */
export type AscDenyReason =
  | "not_allowed"
  | "personal_data"
  | "invalid_path"
  | "invalid_body"
  | "wrong_type"
  | "attribute_not_allowed"
  | "relationship_not_allowed"
  | "included_not_allowed"
  | "value_not_allowed"
  | "typed_confirmation_required"
  | "initial_only";

/** A request the gate refused. Thrown before any token is minted or request sent. */
export class AscWriteDenied extends Error {
  constructor(
    readonly method: string,
    /** The matched path template, or the request path when no rule matched. */
    readonly target: string,
    readonly reason: AscDenyReason,
  ) {
    super(
      `App Store Connect write gate refused ${method} ${target}: ${reason}`,
    );
    this.name = "AscWriteDenied";
  }
}


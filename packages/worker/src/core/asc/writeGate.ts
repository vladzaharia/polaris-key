// ── Matching ─────────────────────────────────────────────────────────────────────────────────

/** A path segment the client may send: a resource type, a relationship name, or an id. */
const SEGMENT = /^[A-Za-z0-9][A-Za-z0-9_-]{0,127}$/;

function templateRegex(template: string): RegExp {
  const body = template
    .split("/")
    .map((s) => (s === "{id}" ? "[A-Za-z0-9][A-Za-z0-9_-]{0,127}" : s))
    .join("/");
  return new RegExp(`^${body}$`);
}

const COMPILED = ASC_WRITE_ALLOW.map((rule) => ({
  rule,
  re: templateRegex(rule.path),
}));

/** Personal data and team membership: refused for every method, reads included. */
function isPersonalData(path: string): boolean {
  // Case-insensitive: a `/v1/Users` spelling is refused too, whatever Apple would answer.
  return /^\/v1\/(users|userinvitations)(\/|$)/i.test(path);
}

/** The allow rule for one method and request path, or null. */
export function findAllowRule(
  method: string,
  path: string,
): AscAllowRule | null {
  for (const { rule, re } of COMPILED)
    if (rule.method === method && re.test(path)) return rule;
  return null;
}

function isPlainObject(v: unknown): v is Record<string, unknown> {
  return typeof v === "object" && v !== null && !Array.isArray(v);
}

function onlyKeys(o: Record<string, unknown>, allowed: readonly string[]) {
  return Object.keys(o).every((k) => allowed.includes(k));
}

const ID = /^[A-Za-z0-9${}._:-]{1,128}$/;

function isIdentifier(v: unknown, type: string): boolean {
  return (
    isPlainObject(v) &&
    onlyKeys(v, ["type", "id"]) &&
    v.type === type &&
    typeof v.id === "string" &&
    ID.test(v.id)
  );
}

/** Check a linkage body (`/relationships/<name>`): identifiers of the rule's type only. */
function checkLinkage(rule: AscAllowRule, body: unknown): AscDenyReason | null {
  if (!isPlainObject(body) || !onlyKeys(body, ["data"])) return "invalid_body";
  const d = body.data;
  const ids = Array.isArray(d) ? d : [d];
  if (ids.length === 0 || ids.length > 200) return "invalid_body";
  return ids.every((i) => isIdentifier(i, rule.type)) ? null : "wrong_type";
}

function checkResource(
  rule: AscAllowRule,
  path: string,
  body: unknown,
  ctx: AscGateContext,
): AscDenyReason | null {
  if (!isPlainObject(body)) return "invalid_body";
  const topKeys = rule.included ? ["data", "included"] : ["data"];
  if (!onlyKeys(body, topKeys)) return "included_not_allowed";
  const data = body.data;
  if (!isPlainObject(data)) return "invalid_body";
  if (!onlyKeys(data, ["type", "id", "attributes", "relationships"]))
    return "invalid_body";
  if (data.type !== rule.type) return "wrong_type";
  if (rule.method === "PATCH") {
    // The body's id must be the path's: a PATCH cannot name one object and change another.
    const pathId = path.split("/").at(-1);
    if (data.id !== pathId) return "invalid_body";
  } else if ("id" in data) {
    return "invalid_body";
  }
  if ("attributes" in data) {
    if (!isPlainObject(data.attributes)) return "invalid_body";
    if (!onlyKeys(data.attributes, rule.attributes))
      return "attribute_not_allowed";
  }
  if ("relationships" in data) {
    const rels = data.relationships;
    if (!isPlainObject(rels)) return "invalid_body";
    for (const [name, rel] of Object.entries(rels)) {
      const type = rule.relationships[name];
      if (type === undefined) return "relationship_not_allowed";
      if (!isPlainObject(rel) || !onlyKeys(rel, ["data"]))
        return "invalid_body";
      const ids = Array.isArray(rel.data) ? rel.data : [rel.data];
      if (ids.length > 200) return "invalid_body";
      if (!ids.every((i) => isIdentifier(i, type))) return "wrong_type";
    }
  }
  if ("included" in body) {
    const inc = body.included;
    if (!Array.isArray(inc) || inc.length > 200) return "invalid_body";
    for (const r of inc)
      if (
        !isPlainObject(r) ||
        typeof r.type !== "string" ||
        !rule.included!.includes(r.type)
      )
        return "included_not_allowed";
  }
  return rule.check ? rule.check(data as unknown as JsonApiData, ctx) : null;
}

function checkConfirm(
  confirm: AscConfirm,
  ctx: AscGateContext,
): AscDenyReason | null {
  switch (confirm) {
    case "plain":
      return null;
    case "typed":
      return ctx.typedConfirmation === true
        ? null
        : "typed_confirmation_required";
    case "initial":
      return ctx.initial === true ? null : "initial_only";
    case "typed-or-initial":
      return ctx.initial === true || ctx.typedConfirmation === true
        ? null
        : "typed_confirmation_required";
  }
}

/**
 * Admit or refuse one App Store Connect request. Throws `AscWriteDenied`; returns the matched
 * rule for a write (null for an admitted read). Pure: no I/O, no token.
 */
export function checkAscRequest(
  method: string,
  path: string,
  body: unknown,
  ctx: AscGateContext = {},
): AscAllowRule | null {
  if (
    !/^\/v[12]\//.test(path) ||
    !path
      .slice(4)
      .split("/")
      .every((s) => SEGMENT.test(s))
  )
    throw new AscWriteDenied(method, path, "invalid_path");
  if (isPersonalData(path))
    throw new AscWriteDenied(method, path, "personal_data");
  if (method === "GET") {
    if (body !== undefined)
      throw new AscWriteDenied(method, path, "invalid_body");
    return null;
  }
  const rule = findAllowRule(method, path);
  if (!rule) throw new AscWriteDenied(method, path, "not_allowed");
  const bodyReason = rule.path.includes("/relationships/")
    ? checkLinkage(rule, body)
    : checkResource(rule, path, body, ctx);
  const reason = bodyReason ?? checkConfirm(rule.confirm, ctx);
  if (reason) throw new AscWriteDenied(method, rule.path, reason);
  return rule;
}

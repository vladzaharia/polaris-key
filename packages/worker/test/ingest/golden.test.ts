const GOLDEN_PATH = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "fixtures",
  "ingest",
  "golden.json",
);
const GOLDEN: Record<string, Captured> = JSON.parse(
  readFileSync(GOLDEN_PATH, "utf8"),
);
const CAPTURE = process.env.INGEST_GOLDEN_CAPTURE === "1";

interface Captured {
  writes: unknown;
  state: unknown;
  result: unknown;
  trips: number;
}

const ingest = ingestFor(SERVICES);

/** Deep-mask a result: strings through `mask`, key order kept. */
function maskDeep(v: unknown): unknown {
  if (Array.isArray(v)) return v.map(maskDeep);
  if (v && typeof v === "object")
    return Object.fromEntries(
      Object.entries(v).map(([k, x]) => [k, maskDeep(x)]),
    );
  return mask(v);
}

/** Run `act` against a recording view of `w.db` and capture what it did. */
async function record(
  w: Linked,
  act: (db: RecordingDb) => Promise<unknown>,
): Promise<Captured> {
  const rdb = new RecordingDb(w.db);
  const result = await act(rdb);
  return {
    writes: rdb.byTable(),
    state: await rdb.dump(),
    result: maskDeep(result),
    trips: rdb.trips,
  };
}

function check(name: string, got: Captured): void {
  const want = GOLDEN[name];
  if (!want) {
    if (!CAPTURE) throw new Error(`no golden for "${name}"; capture it once`);
    GOLDEN[name] = got;
    writeFileSync(GOLDEN_PATH, `${JSON.stringify(GOLDEN, null, 2)}\n`);
    return;
  }
  const norm = JSON.parse(JSON.stringify(got)) as Captured;
  if (process.env.INGEST_GOLDEN_DUMP)
    writeFileSync(
      `${process.env.INGEST_GOLDEN_DUMP}/${name}.json`,
      JSON.stringify(norm, null, 1),
    );
  expect(norm.writes).toEqual(want.writes);
  expect(norm.state).toEqual(want.state);
  expect(norm.result).toEqual(want.result);
  expect(got.trips).toBeLessThanOrEqual(want.trips);
}

const link =
  (w: Linked, create?: NonNullable<Parameters<typeof linkRepo>[6]>["create"]) =>
  (db: RecordingDb) =>
    linkRepo(w.env, db, URL_, NOW, w.remote.fetch, ingest, { create });
const resync =
  (w: Linked, at = NOW + 60) =>
  (db: RecordingDb) =>
    resyncRepo(w.env, db, SLUG, at, w.remote.fetch, ingest);

async function linked(files: Record<string, string>): Promise<Linked> {
  const w = fresh(files);
  const res = await linkRepo(w.env, w.db, URL_, NOW, w.remote.fetch, ingest);
  expect(res.ok, JSON.stringify(res)).toBe(true);
  return w;
}


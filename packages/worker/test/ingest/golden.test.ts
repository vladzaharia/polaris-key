/**
 * P0-26: the manifest ingest, captured before it moved.
 *
 * Link, resync (webhook, console and link-existing), the deploy hook and the dry runs each write a
 * product's `.pkey/` into D1. P0-26 puts one Core pipeline under all of them, and the move must
 * not change a statement. This file runs each path from a fixed starting point and compares, per
 * scenario, against `test/fixtures/ingest/golden.json`, captured ONCE from the pre-pipeline code
 * (plans/P0-26.md §4):
 *
 *   1. each table's writes, in order (the order ACROSS tables is free; `audit` is a multiset);
 *   2. the end state of every table written;
 *   3. the result object, ids masked (random ids, sealed envelopes and minted keys);
 *   4. D1 round trips, which may not grow.
 *
 * The file is never regenerated by a script. A first run with `INGEST_GOLDEN_CAPTURE=1` adds a
 * scenario that has no entry and never overwrites one. Every sanctioned edit is listed here:
 *
 *   - audit rows in the end-state dump are sorted (D4: audit is a multiset; the pipeline writes
 *     them in its own order). Every entry's `state.audit` was re-sorted in place, nothing else.
 *   - P0-26a merged the sec snapshot scrub (sec/manifest-snapshot-redact) and main's U-31, and
 *     those entries were re-captured deliberately, each for exactly these differences:
 *     the snapshot's `manifest_json` holds `[redacted]` where a profile secret value was (1, 3,
 *     4, 5, 8, 9-*), and a resync's edge-mint DELETE and INSERT carry U-31's
 *     `config.catalog` claim guard (3, 4, 5, 6a, 8, 9-*, 10a; 5's end state
 *     keeps the console's recipe).
 *   - 14a/14b/14c (plans/P0-26.md D5, deltas 2 and 3): the create dry run parses with
 *     reservedDisplayNames, and the resync and link dry runs list every policy refusal, not
 *     only the first. Captured from the pipeline's plan when the deltas landed; the pre-delta
 *     behaviour had no scenario.
 *   - 11a/11b: the deploy hook's snapshot scrub reads the active schema, one more D1 round trip
 *     (sec/manifest-snapshot-redact); only the trip count moved.
 *   - CM-29 (integration, 2026-10-17): the service table gained `commerce` (off by default), so
 *     every captured services JSON carries `"commerce":{"enabled":false}`, and the 9-* service
 *     switch audit summaries cut off at the same length one key later. 1-6, 8-10 and 11-12 were
 *     re-captured for that alone (checked: with the commerce member removed the entries are
 *     unchanged, except the 9-* summaries' truncation point).
 *   - 13-link-secret-default (plans/P0-26.md D5, delta 1): link screens the catalog for delivery
 *     issues, as resync and the console do. Captured from the pre-pipeline code (the link
 *     succeeded), then re-captured from the pipeline when the delta landed (the link refuses).
 */

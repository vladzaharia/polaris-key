// A-17a (notes/S-14 §7.5): extract the WRITE operations of Apple's App Store Connect OpenAPI
// document into the pinned fixture the write gate's classification test reads
// (`test/fixtures/asc/openapi-writes.json`). The full document is 7 MB and Apple's to publish, so
// only what the gate needs is committed: method, path template, operation id and the request
// body's resource type, attribute keys and relationship keys.
//
//   curl -sSLo /tmp/asc.zip https://developer.apple.com/sample-code/app-store-connect/app-store-connect-openapi-specification.zip
//   (cd /tmp && unzip -o asc.zip)
//   node scripts/asc-spec-writes.mjs /tmp/openapi.oas.json            # refuses an unpinned spec
//   node scripts/asc-spec-writes.mjs /tmp/openapi.oas.json --accept    # a NEW spec version: also
//                                                                      # bump ASC_SPEC_PIN in
//                                                                      # core/asc/writeGate.ts
//
// The output is generated: never edit it by hand. A spec bump is a THREAT-MODEL §9 review
// trigger, and the classification test fails until every new write operation is classified.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/** The spec the committed fixture was generated from (S-14 §13). */
const PINNED_SHA256 =
  "1e8ef250d6a41bab0f5670b669abf3f06298ef129c8455ba258149fda86927b2";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "..", "test", "fixtures", "asc", "openapi-writes.json");

const src = process.argv[2];
if (!src) {
  console.error(
    "usage: node scripts/asc-spec-writes.mjs <openapi.oas.json> [--accept]",
  );
  process.exit(2);
}
const raw = readFileSync(src);
const sha256 = createHash("sha256").update(raw).digest("hex");
if (sha256 !== PINNED_SHA256 && !process.argv.includes("--accept")) {
  console.error(
    `spec SHA-256 ${sha256} is not the pinned ${PINNED_SHA256}; pass --accept to adopt it (and classify every new write)`,
  );
  process.exit(1);
}

const spec = JSON.parse(raw.toString("utf8"));
const schemas = spec.components.schemas;
const deref = (o) => (o && o.$ref ? schemas[o.$ref.split("/").pop()] : o);

const WRITE_METHODS = ["post", "patch", "put", "delete"];
const operations = [];
for (const [path, ops] of Object.entries(spec.paths)) {
  for (const m of WRITE_METHODS) {
    const op = ops[m];
    if (!op) continue;
    const bodyRef = op.requestBody?.content?.["application/json"]?.schema;
    const body = deref(bodyRef);
    const data = deref(body?.properties?.data);
    const entry = {
      method: m.toUpperCase(),
      path,
      operationId: op.operationId ?? null,
      requestSchema: bodyRef?.$ref ? bodyRef.$ref.split("/").pop() : null,
      type: null,
      attributes: [],
      relationships: [],
      // `/relationships/<name>`: a JSON:API linkage body (`data` is identifiers only).
      linkage: path.includes("/relationships/"),
      included: Boolean(body?.properties?.included),
    };
    if (data?.type === "array") {
      entry.type = deref(data.items)?.properties?.type?.enum?.[0] ?? null;
    } else if (data?.properties) {
      entry.type = data.properties.type?.enum?.[0] ?? null;
      entry.attributes = Object.keys(
        deref(data.properties.attributes)?.properties ?? {},
      ).sort();
      entry.relationships = Object.keys(
        deref(data.properties.relationships)?.properties ?? {},
      ).sort();
    }
    operations.push(entry);
  }
}
operations.sort((a, b) =>
  a.path === b.path
    ? a.method.localeCompare(b.method)
    : a.path.localeCompare(b.path),
);

const out = {
  $comment:
    "GENERATED by packages/worker/scripts/asc-spec-writes.mjs from Apple's App Store Connect OpenAPI document. Do not edit by hand.",
  source: {
    title: spec.info.title,
    version: spec.info.version,
    sha256,
    paths: Object.keys(spec.paths).length,
  },
  operations,
};
writeFileSync(OUT, JSON.stringify(out, null, 2) + "\n");
console.log(
  `wrote ${operations.length} write operations (${spec.info.title} ${spec.info.version}, ${sha256.slice(0, 12)}…) to ${OUT}`,
);

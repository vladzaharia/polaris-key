// A-18e (notes/S-15 §3, §4.1): extract the WRITE methods of Google's androidpublisher v3 discovery
// document into the pinned fixture the Play write gate's classification reads
// (`test/fixtures/play/discovery-writes.json`; `test/storefront/conformance.test.ts` item 1). The
// document is public and 600 KB, so only what the gate needs is committed: the HTTP method, the
// path template (`/` + `flatPath`), the method id and whether it takes a media upload.
//
//   curl -sSo /tmp/play-discovery.json 'https://androidpublisher.googleapis.com/$discovery/rest?version=v3'
//   node scripts/play-spec-writes.mjs /tmp/play-discovery.json            # refuses an unpinned doc
//   node scripts/play-spec-writes.mjs /tmp/play-discovery.json --accept   # a NEW revision: also bump
//                                                                         # PLAY_SPEC_PIN in
//                                                                         # core/storefront/rules/googlePlay.ts
//
// THE PIN IS OVER CANONICAL JSON. Google serves the same revision with its object keys in a
// different order on every fetch (two fetches of revision 20261001 on 2026-10-04 hashed
// cafd73b4… and 98ccad1c…, and S-15's own scan bcbce36e…), so a hash of the raw bytes pins
// nothing. The pin is the SHA-256 of the document re-serialised with every object's keys sorted and
// no whitespace, plus the `revision`; both must match.
//
// The output is generated: never edit it by hand. A revision bump is a THREAT-MODEL §9 review
// trigger, and the classification test fails until every new write method is classified.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/** The document the committed fixture was generated from. */
const PINNED = {
  revision: "20261001",
  sha256: "b8a7f31d74baff7eb4a407b28b649975a769dbfba30d6a408cc3220bc6605ec4",
};

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(
  HERE,
  "..",
  "test",
  "fixtures",
  "play",
  "discovery-writes.json",
);

/** JSON with every object's keys sorted, no whitespace: stable across Google's key orders. */
function canonical(v) {
  if (Array.isArray(v)) return `[${v.map(canonical).join(",")}]`;
  if (v && typeof v === "object")
    return `{${Object.keys(v)
      .sort()
      .map((k) => `${JSON.stringify(k)}:${canonical(v[k])}`)
      .join(",")}}`;
  return JSON.stringify(v);
}

const src = process.argv[2];
if (!src) {
  console.error(
    "usage: node scripts/play-spec-writes.mjs <play-discovery.json> [--accept]",
  );
  process.exit(2);
}
const doc = JSON.parse(readFileSync(src, "utf8"));
const sha256 = createHash("sha256").update(canonical(doc)).digest("hex");
if (
  (sha256 !== PINNED.sha256 || doc.revision !== PINNED.revision) &&
  !process.argv.includes("--accept")
) {
  console.error(
    `discovery revision ${doc.revision} (canonical SHA-256 ${sha256}) is not the pinned ${PINNED.revision} (${PINNED.sha256}); pass --accept to adopt it (and classify every new write)`,
  );
  process.exit(1);
}

const operations = [];
let total = 0;
function walk(resources, prefix) {
  for (const [name, r] of Object.entries(resources ?? {})) {
    const p = prefix ? `${prefix}.${name}` : name;
    for (const [m, def] of Object.entries(r.methods ?? {})) {
      total++;
      if (def.httpMethod === "GET") continue;
      operations.push({
        method: def.httpMethod,
        path: `/${def.flatPath ?? def.path}`,
        id: `${p}.${m}`,
        upload: def.supportsMediaUpload === true,
      });
    }
    walk(r.resources, p);
  }
}
walk(doc.resources, "");
operations.sort((a, b) =>
  a.path === b.path
    ? a.method.localeCompare(b.method)
    : a.path.localeCompare(b.path),
);

const out = {
  $comment:
    "GENERATED by packages/worker/scripts/play-spec-writes.mjs from Google's androidpublisher v3 discovery document. Do not edit by hand.",
  source: {
    title: doc.title,
    version: doc.revision,
    sha256,
    methods: total,
  },
  operations,
};
writeFileSync(OUT, JSON.stringify(out, null, 2) + "\n");
console.log(
  `wrote ${operations.length} write methods of ${total} (${doc.title} ${doc.revision}, ${sha256.slice(0, 12)}…) to ${OUT}`,
);

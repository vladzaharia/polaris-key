#!/usr/bin/env node
/**
 * Writes `dist/dev/server.mjs` (SP-41): the `pkey dev` server, one esbuild bundle of the real
 * Worker router (`packages/worker/src`), its in-memory mocks and the dev shell
 * (`packages/worker/dev`), with every D1 migration inlined. Node >= 22.13 provides SQLite
 * (`node:sqlite`), so there is no native addon and nothing to install.
 *
 * It is an artifact of the CLI package, not a source file, and the Action bundle never contains it
 * (`pkey dev` loads it by a path built at run time). The production Worker bundle never contains
 * it either: `packages/cli/test/devBundle.test.ts` bundles `src/index.ts` and looks for it.
 *
 * The workspace packages the Worker imports resolve to their BUILT `dist/`, so this runs after
 * `tsc` and after the dependencies' own builds (turbo's `^build`).
 */
import { readdir, readFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const pkgDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const worker = path.resolve(pkgDir, "..", "worker");
// `--out <file>`: a test builds its own copy, so it never depends on `pnpm build` having run.
const outArg = process.argv.indexOf("--out");
const outFile =
  outArg !== -1 && process.argv[outArg + 1]
    ? path.resolve(process.argv[outArg + 1])
    : path.join(pkgDir, "dist", "dev", "server.mjs");

const migrations = {
  name: "pkey-dev-migrations",
  setup(b) {
    b.onResolve({ filter: /^pkey-dev:migrations$/ }, () => ({
      path: "migrations",
      namespace: "pkey-dev",
    }));
    b.onLoad({ filter: /.*/, namespace: "pkey-dev" }, async () => {
      const dir = path.join(worker, "migrations");
      const names = (await readdir(dir)).filter((f) => f.endsWith(".sql")).sort();
      const sql = await Promise.all(
        names.map((n) => readFile(path.join(dir, n), "utf8")),
      );
      return {
        contents: `export const MIGRATIONS = ${JSON.stringify(sql)};`,
        loader: "js",
        resolveDir: worker,
      };
    });
  },
};

await mkdir(path.dirname(outFile), { recursive: true });
await build({
  entryPoints: [path.join(worker, "dev", "index.ts")],
  outfile: outFile,
  bundle: true,
  platform: "node",
  target: "node22",
  format: "esm",
  logLevel: "warning",
  loader: { ".wasm": "binary" },
  plugins: [migrations],
  banner: {
    js: [
      "// GENERATED by packages/cli/scripts/bundle-dev.mjs. DO NOT EDIT.",
      'import { createRequire as __pkeyCreateRequire } from "node:module";',
      "const require = __pkeyCreateRequire(import.meta.url);",
    ].join("\n"),
  },
});
if (outArg === -1)
  console.log(`bundle-dev: wrote ${path.relative(process.cwd(), outFile)}`);

#!/usr/bin/env node
/**
 * Writes `actions/publish/dist/index.js` (P2-06): one esbuild bundle of the `pkey` CLI that is
 * both the `polaris-key/publish` GitHub Action and the standalone `pkey.mjs` the `pkey` image
 * ships (packages/cli/image). The file is GENERATED and committed (an Action runs its committed
 * `dist/`, with no install step); `--check` rebuilds it in memory and fails on any difference,
 * so a CLI change that forgets to rebundle fails CI instead of shipping a stale Action.
 *
 *   pnpm --filter @polaris-key/cli bundle:action             # rewrite the bundle
 *   pnpm --filter @polaris-key/cli bundle:action -- --check  # freshness gate (CI)
 *
 * Inputs: `src/bin/standalone.ts` and everything it imports — the workspace packages resolve to
 * their BUILT `dist/`, so run `pnpm build` first — plus the `.pkey/` JSON Schemas, inlined as
 * `__PKEY_EMBEDDED_SCHEMAS__` for `pkey manifest schemas`.
 *
 * Licences: the bundle inlines third-party code (yaml, ISC; the Zstandard decoder, BSD). Their
 * notices live in `actions/publish/THIRD_PARTY_NOTICES` and are also appended to the bundle as a
 * trailing legal comment, so the standalone `pkey.mjs` carries them without the Action directory.
 * Any `/*!` or `@license` comments in bundled sources are kept at the end too (`legalComments`).
 */

import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const pkgDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(pkgDir, "..", "..");
// `--out <file>` writes (or checks) another path — the test that proves `--check` fails on a
// stale bundle uses it so it never touches the committed file.
const outArg = process.argv.indexOf("--out");
const outFile =
  outArg !== -1 && process.argv[outArg + 1]
    ? path.resolve(process.argv[outArg + 1])
    : path.join(repoRoot, "actions", "publish", "dist", "index.js");
const schemaDir = path.join(
  repoRoot,
  "packages",
  "shared-manifest",
  "schemas",
  "v1",
);

const noticesFile = path.join(
  repoRoot,
  "actions",
  "publish",
  "THIRD_PARTY_NOTICES",
);

const BANNER = [
  "#!/usr/bin/env node",
  "// GENERATED by packages/cli/scripts/bundle-action.mjs from @polaris-key/cli. DO NOT EDIT.",
  "// Regenerate: pnpm build && pnpm --filter @polaris-key/cli bundle:action",
  "// Freshness: pnpm --filter @polaris-key/cli bundle:action -- --check",
  // Bundled CommonJS dependencies may `require` Node builtins; an ESM bundle has no `require`.
  'import { createRequire as __pkeyCreateRequire } from "node:module";',
  "const require = __pkeyCreateRequire(import.meta.url);",
].join("\n");

/** The third-party notices, as one trailing legal comment. */
async function footer() {
  const notices = (await readFile(noticesFile, "utf8")).trimEnd();
  if (notices.includes("*/"))
    throw new Error(`${noticesFile} must not contain "*/"`);
  return `/*!\n${notices}\n*/`;
}

async function schemas() {
  const names = (await readdir(schemaDir))
    .filter((n) => n.endsWith(".schema.json"))
    .sort();
  const out = {};
  for (const name of names)
    out[name] = await readFile(path.join(schemaDir, name), "utf8");
  return out;
}

/**
 * `@polaris-key/zstd-wasm`'s Node entry reads `zdec.wasm` beside itself, which a one-file bundle
 * has no copy of. The chunk lints (P4-22) decode with it, so the bundle resolves the package to
 * this module instead: the same decoder over the same committed `zdec.wasm`, inlined as bytes
 * (esbuild's `binary` loader).
 */
const zstdWasmEmbedded = {
  name: "zstd-wasm-embedded",
  setup(b) {
    b.onResolve({ filter: /^@polaris-key\/zstd-wasm$/ }, () => ({
      path: "zstd-wasm-embedded",
      namespace: "pkey-zstd-wasm",
    }));
    b.onLoad({ filter: /.*/, namespace: "pkey-zstd-wasm" }, () => ({
      resolveDir: pkgDir,
      loader: "js",
      contents: [
        'import { createZstdWasm } from "@polaris-key/zstd-wasm/core";',
        'import bytes from "@polaris-key/zstd-wasm/zdec.wasm";',
        'export { ZstdWasmError } from "@polaris-key/zstd-wasm/core";',
        "let decoder = null;",
        "const get = () => (decoder ??= createZstdWasm(new WebAssembly.Module(bytes)));",
        "export const decode = (frame, size) => get().decode(frame, size);",
        "export const decodeWithPrefix = (frame, prefix, size, windowLogMax) =>",
        "  get().decodeWithPrefix(frame, prefix, size, windowLogMax);",
        "export const version = () => get().version();",
      ].join("\n"),
    }));
  },
};

async function bundle() {
  const result = await build({
    plugins: [zstdWasmEmbedded],
    loader: { ".wasm": "binary" },
    absWorkingDir: pkgDir,
    entryPoints: ["src/bin/standalone.ts"],
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node20",
    write: false,
    minify: false,
    sourcemap: false,
    legalComments: "eof",
    charset: "utf8",
    logLevel: "warning",
    banner: { js: BANNER },
    footer: { js: await footer() },
    define: { __PKEY_EMBEDDED_SCHEMAS__: JSON.stringify(await schemas()) },
  });
  return result.outputFiles[0].text;
}

const check = process.argv.includes("--check");
const text = await bundle();
if (check) {
  let current = null;
  try {
    current = await readFile(outFile, "utf8");
  } catch {
    // Missing counts as stale.
  }
  if (current !== text) {
    console.error(
      `${path.relative(repoRoot, outFile)} is stale${current === null ? " (missing)" : ""}. ` +
        "Run: pnpm build && pnpm --filter @polaris-key/cli bundle:action",
    );
    process.exit(1);
  }
  console.log(`${path.relative(repoRoot, outFile)} is fresh.`);
} else {
  await mkdir(path.dirname(outFile), { recursive: true });
  await writeFile(outFile, text, "utf8");
  console.log(
    `Wrote ${path.relative(repoRoot, outFile)} (${Buffer.byteLength(text)} bytes).`,
  );
}

#!/usr/bin/env node
/**
 * Writes `actions/publish/dist/index.js` (P2-06): one esbuild bundle of the `pkey` CLI that is
 * both the `polaris-key/publish` GitHub Action and the standalone `pkey.mjs` attached to the
 * monorepo's GitHub releases. The file is GENERATED and committed (an Action runs its committed
 * `dist/`, with no install step); `--check` rebuilds it in memory and fails on any difference,
 * so a CLI change that forgets to rebundle fails CI instead of shipping a stale Action.
 *
 *   pnpm --filter @polaris-key/cli bundle:action             # rewrite the bundle
 *   pnpm --filter @polaris-key/cli bundle:action -- --check  # freshness gate (CI)
 *
 * Inputs: `src/bin/standalone.ts` and everything it imports — the workspace packages resolve to
 * their BUILT `dist/`, so run `pnpm build` first — plus the `.pkey/` JSON Schemas, inlined as
 * `__PKEY_EMBEDDED_SCHEMAS__` for `pkey manifest schemas`.
 */

import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const pkgDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(pkgDir, "..", "..");
// `--out <file>` writes (or checks) another path — the test that proves `--check` fails on a
// stale bundle uses it so it never touches the committed file.
const outArg = process.argv.indexOf("--out");
const outFile =
  outArg !== -1 && process.argv[outArg + 1]
    ? path.resolve(process.argv[outArg + 1])
    : path.join(repoRoot, "actions", "publish", "dist", "index.js");
const schemaDir = path.join(repoRoot, "packages", "shared-manifest", "schemas", "v1");

const BANNER = [
  "#!/usr/bin/env node",
  "// GENERATED by packages/cli/scripts/bundle-action.mjs from @polaris-key/cli. DO NOT EDIT.",
  "// Regenerate: pnpm build && pnpm --filter @polaris-key/cli bundle:action",
  "// Freshness: pnpm --filter @polaris-key/cli bundle:action -- --check",
  // Bundled CommonJS dependencies may `require` Node builtins; an ESM bundle has no `require`.
  'import { createRequire as __pkeyCreateRequire } from "node:module";',
  "const require = __pkeyCreateRequire(import.meta.url);",
].join("\n");

async function schemas() {
  const names = (await readdir(schemaDir)).filter((n) => n.endsWith(".schema.json")).sort();
  const out = {};
  for (const name of names) out[name] = await readFile(path.join(schemaDir, name), "utf8");
  return out;
}

async function bundle() {
  const result = await build({
    absWorkingDir: pkgDir,
    entryPoints: ["src/bin/standalone.ts"],
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node20",
    write: false,
    minify: false,
    sourcemap: false,
    legalComments: "inline",
    charset: "utf8",
    logLevel: "warning",
    banner: { js: BANNER },
    define: { __PKEY_EMBEDDED_SCHEMAS__: JSON.stringify(await schemas()) },
  });
  return result.outputFiles[0].text;
}

const check = process.argv.includes("--check");
const text = await bundle();
if (check) {
  let current = null;
  try {
    current = await readFile(outFile, "utf8");
  } catch {
    // Missing counts as stale.
  }
  if (current !== text) {
    console.error(
      `${path.relative(repoRoot, outFile)} is stale${current === null ? " (missing)" : ""}. ` +
        "Run: pnpm build && pnpm --filter @polaris-key/cli bundle:action",
    );
    process.exit(1);
  }
  console.log(`${path.relative(repoRoot, outFile)} is fresh.`);
} else {
  await mkdir(path.dirname(outFile), { recursive: true });
  await writeFile(outFile, text, "utf8");
  console.log(`Wrote ${path.relative(repoRoot, outFile)} (${Buffer.byteLength(text)} bytes).`);
}

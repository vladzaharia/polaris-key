describe("CIEDE2000", () => {
  it.each(SHARMA)(
    "Sharma 2005: (%f, %f, %f) vs (%f, %f, %f) = %f",
    (l1, a1, b1, l2, a2, b2, want) => {
      const x = { l: l1, a: a1, b: b1 };
      const y = { l: l2, a: a2, b: b2 };
      expect(deltaE2000Lab(x, y)).toBeCloseTo(want, 4);
      expect(deltaE2000Lab(y, x)).toBeCloseTo(want, 4);
    },
  );

  it("sRGB to Lab hits the D65 anchors", () => {
    const white = hexToLab("#ffffff");
    expect(white.l).toBeCloseTo(100, 3);
    expect(white.a).toBeCloseTo(0, 3);
    expect(white.b).toBeCloseTo(0, 3);
    expect(hexToLab("#000000").l).toBeCloseTo(0, 6);
    // sRGB red: L* 53.24, a* 80.09, b* 67.20 (Lindbloom).
    const red = hexToLab("#ff0000");
    expect(red.l).toBeCloseTo(53.24, 1);
    expect(red.a).toBeCloseTo(80.09, 1);
    expect(red.b).toBeCloseTo(67.2, 1);
    expect(deltaE2000("#123456", "#123456")).toBe(0);
  });
});

import { describe, expect, it } from "vitest";
import type { SigningKeyDto } from "../src/api.js";
import {
  SDK_OPTIONS,
  codeLanguage,
  sdkSetup,
  trustPins,
} from "../src/console/sections/core/model/sdkQuickStart.js";

const key = (kid: string, status: string): SigningKeyDto => ({
  kid,
  status,
  alg: "EdDSA",
  publicKey: `PUB-${kid}`,
  createdAt: 1,
  activateAfter: null,
  activatedAt: null,
  retiredAt: null,
  revokedAt: null,
});

const input = {
  slug: "tonebox",
  origin: "https://key.plrs.im",
  pins: [
    { kid: "tb-a", publicKey: "PUB-A" },
    { kid: "tb-b", publicKey: "PUB-B" },
  ],
  services: ["license", "config"] as const,
};

describe("SDK quick start: install (D17)", () => {
  it("every SDK installs from pkg.plrs.im, its namespace routed there first", () => {
    for (const { value } of SDK_OPTIONS) {
      const snippets = sdkSetup(value, input).install;
      expect(snippets.length, value).toBeGreaterThan(0);
      expect(snippets[0]!.code, value).toContain("https://pkg.plrs.im/");
      for (const s of snippets) {
        expect(s.code, value).not.toMatch(/registry\.npmjs\.org|pypi\.org/);
        expect(s.code, value).not.toContain("--extra-index-url");
      }
    }
  });

  it("Node routes the @polaris-key scope before npm install", () => {
    const [npmrc, install] = sdkSetup("node", input).install;
    expect(npmrc!.filename).toBe(".npmrc");
    expect(npmrc!.code).toBe(
      "@polaris-key:registry=https://pkg.plrs.im/npm/polaris-key/",
    );
    expect(install!.code).toBe("npm install @polaris-key/node");
  });
});

describe("SDK quick start: trust pins (D16)", () => {
  it("pins every active and staged key, active first, never a retired one", () => {
    expect(
      trustPins(
        [key("c", "retired"), key("b", "staged"), key("a", "active")],
        null,
      ),
    ).toEqual([
      { kid: "a", publicKey: "PUB-a" },
      { kid: "b", publicKey: "PUB-b" },
    ]);
  });

  it("falls back to the product's active key while the inventory is unread", () => {
    expect(trustPins(undefined, { kid: "a", publicKey: "PUB" })).toEqual([
      { kid: "a", publicKey: "PUB" },
    ]);
    expect(trustPins([], { kid: "a" })).toEqual([]);
  });
});

describe("SDK quick start: configuration and start (SP-33a)", () => {
  it("every SDK's configuration carries every pin, on one generator with pkey sdk", () => {
    for (const { value } of SDK_OPTIONS) {
      const { config, start } = sdkSetup(value, input);
      expect(config.code, value).toContain("PUB-A");
      expect(config.code, value).toContain("PUB-B");
      expect(config.code, value).toContain("GENERATED by `pkey sdk");
      expect(start.lane, value).not.toBe("server");
      expect(start.docs, value).toMatch(/^\/docs\/.*\/$/);
    }
  });

  it("React carries the trust pins in the provider config, so bearer mode verifies (P0-47)", () => {
    const { config, start } = sdkSetup("react", input);
    expect(config.code).toContain("trust: { pinnedKeys },");
    expect(config.code).toContain('"tb-a": "PUB-A"');
    expect(start.code).toContain("<PolarisKeyProvider config={polarisKey}>");
    expect(start.code).toContain(
      'import { PolarisKeyGate } from "@polaris-key/react/kit";',
    );
  });

  it("names the base URL off production", () => {
    const { config } = sdkSetup("python", {
      ...input,
      origin: "https://key-staging.plrs.im",
    });
    expect(config.code).toContain('BASE_URL = "https://key-staging.plrs.im"');
  });

  it("warns when Update is on without release keys, and when there is no key yet", () => {
    expect(
      sdkSetup("node", { ...input, services: ["license", "update"] }).warnings
        .length,
    ).toBe(1);
    expect(sdkSetup("node", { ...input, pins: [] }).warnings[0]).toMatch(
      /no signing key/,
    );
    expect(sdkSetup("node", input).warnings).toEqual([]);
  });

  it("highlights TypeScript and shows the rest as text", () => {
    expect(codeLanguage("tsx")).toBe("ts");
    expect(codeLanguage("python")).toBe("text");
  });
});

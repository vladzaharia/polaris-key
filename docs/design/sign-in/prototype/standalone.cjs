// Builds standalone.html: the prototype as one self-contained, shareable page (the stylesheets,
// the tokens, the script and the two fonts inlined as data URIs). Run after editing the prototype:
//
//   node docs/design/sign-in/prototype/standalone.cjs && pnpm exec prettier --write docs/design/sign-in/prototype/standalone.html
//
// index.html stays the CSP-safe reference (external files only); standalone.html trades that for
// portability, so it drops the CSP meta.
const fs = require("node:fs");
const path = require("node:path");

const dir = __dirname;
function inlineCss(file) {
  const base = path.dirname(file);
  let css = fs.readFileSync(file, "utf8");
  css = css.replace(/@import url\("([^"]+)"\);/g, (_, rel) =>
    inlineCss(path.resolve(base, rel)),
  );
  return css.replace(/url\("([^"]+\.woff2)"\)/g, (_, rel) => {
    const data = fs.readFileSync(path.resolve(base, rel)).toString("base64");
    return `url("data:font/woff2;base64,${data}")`;
  });
}
let html = fs.readFileSync(path.join(dir, "index.html"), "utf8");
html = html.replace(
  /\s*<meta\s+http-equiv="Content-Security-Policy"[\s\S]*?\/>/,
  "",
);
html = html.replace(
  /<link rel="stylesheet" href="proto.css" \/>/,
  () => `<style>\n${inlineCss(path.join(dir, "proto.css"))}\n</style>`,
);
html = html.replace(
  /<script src="proto.js" defer><\/script>/,
  () =>
    `<script defer src="data:text/javascript;base64,${fs
      .readFileSync(path.join(dir, "proto.js"))
      .toString("base64")}"></script>`,
);
html = html.replace(
  "<!doctype html>",
  "<!doctype html>\n<!-- GENERATED by standalone.cjs from index.html, proto.css and proto.js. Do not edit. -->",
);
fs.writeFileSync(path.join(dir, "standalone.html"), html);
console.log(`standalone.html: ${(html.length / 1024).toFixed(0)} KB`);

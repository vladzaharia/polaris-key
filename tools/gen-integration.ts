// The integration content goldens (SP-33a, SDX-02): every block `renderUsage` renders today, written
// as a file per SDK, lane and feature under packages/shared-manifest/test/fixtures/integration/, plus
// index.json listing them. The docs' generated blocks and the TypeScript and Python compile lanes
// (packages/docs/test/integrationGoldens.test.ts) read these files, so a change to a snippet shows
// in review and can never reach the docs uncompiled.
//
//   pnpm gen integration          write
//   pnpm gen integration --check  exit 1 on any difference, write nothing

import {
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import {
  allUsageBlocks,
  type IntegrationBlock,
} from "../packages/shared-manifest/src/integration/index.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const GOLDENS_DIR = join(
  ROOT,
  "packages/shared-manifest/test/fixtures/integration",
);

const EXT: Record<IntegrationBlock["language"], string> = {
  ts: "ts",
  tsx: "tsx",
  python: "py",
  swift: "swift",
  kotlin: "kt",
  gdscript: "gd",
};
const COMMENT: Record<IntegrationBlock["language"], string> = {
  ts: "//",
  tsx: "//",
  python: "#",
  swift: "//",
  kotlin: "//",
  gdscript: "#",
};

/** The golden's path under GOLDENS_DIR. */
export function goldenPath(b: IntegrationBlock): string {
  return `${b.sdk}/${b.lane}/${b.feature}${b.framework ? `.${b.framework}` : ""}.${EXT[b.language]}`;
}

/** The golden's bytes: the block under a GENERATED banner. */
export function goldenText(b: IntegrationBlock): string {
  return `${COMMENT[b.language]} GENERATED by \`pnpm gen integration\` from renderUsage. Do not edit.\n${b.code}`;
}

/** Every file the family owns, path (relative to GOLDENS_DIR) to bytes. */
export function renderGoldens(): Map<string, string> {
  const files = new Map<string, string>();
  const blocks = allUsageBlocks();
  for (const b of blocks) files.set(goldenPath(b), goldenText(b));
  const index = blocks.map((b) => ({
    id: b.id,
    file: goldenPath(b),
    feature: b.feature,
    sdk: b.sdk,
    lane: b.lane,
    framework: b.framework,
    language: b.language,
    title: b.title,
    docs: b.docs,
    status: b.status,
    compiled: b.compiled,
  }));
  files.set("index.json", `${JSON.stringify(index, null, 2)}\n`);
  return files;
}

function existing(dir: string): string[] {
  const out: string[] = [];
  const walk = (d: string): void => {
    let entries;
    try {
      entries = readdirSync(d, { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      const p = join(d, e.name);
      if (e.isDirectory()) walk(p);
      else out.push(relative(dir, p));
    }
  };
  walk(dir);
  return out.sort();
}

function main(): void {
  const check = process.argv.includes("--check");
  const want = renderGoldens();
  const have = existing(GOLDENS_DIR);
  const stale: string[] = [];
  for (const [path, text] of want) {
    let current: string | undefined;
    try {
      current = readFileSync(join(GOLDENS_DIR, path), "utf8");
    } catch {
      current = undefined;
    }
    if (current === text) continue;
    stale.push(path);
    if (!check) {
      mkdirSync(dirname(join(GOLDENS_DIR, path)), { recursive: true });
      writeFileSync(join(GOLDENS_DIR, path), text);
    }
  }
  for (const path of have)
    if (!want.has(path)) {
      stale.push(path);
      if (!check) rmSync(join(GOLDENS_DIR, path));
    }
  if (check && stale.length > 0) {
    for (const p of stale)
      console.error(
        `stale: test/fixtures/integration/${p} — run \`pnpm gen integration\``,
      );
    process.exit(1);
  }
  console.log(
    check
      ? `integration goldens are current (${want.size} files)`
      : `wrote ${stale.length} of ${want.size} integration golden files`,
  );
}

if (
  process.argv[1] !== undefined &&
  fileURLToPath(import.meta.url) === process.argv[1]
)
  main();

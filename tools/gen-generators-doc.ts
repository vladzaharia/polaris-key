// Renders the generator registry (tools/generators.ts) as two committed documents:
//
//   packages/docs/src/content/docs/reference/generators.mdx   the reference page
//   AGENTS.md                                                 every block in BLOCKS, each between its
//                                                             `<name>:start` / `<name>:end` markers
//   tools/lint/generated.json                                 every family's output globs, for the
//                                                             dependency-free lint-debt script
//
//   pnpm gen registry-docs            # write both
//   pnpm gen registry-docs --check    # exit 1 when either is stale

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";
import { GENERATORS, type Cmd, type Generator } from "./generators.js";
import { STEPS, type GateContext, type GateStep } from "./gate.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const PAGE_PATH =
  "packages/docs/src/content/docs/reference/generators.mdx";
export const AGENTS_PATH = "AGENTS.md";
export const SNAPSHOT_PATH = "tools/lint/generated.json";

/** The registry's generated outputs as a JSON snapshot: lint-debt.mjs is plain Node and cannot import TS. */
export function snapshotSource(): string {
  const globs = [...new Set(GENERATORS.flatMap((g) => g.outputs))].sort();
  return JSON.stringify(
    {
      $comment:
        "GENERATED by `pnpm gen registry-docs` from tools/generators.ts; do not edit. Every family's output globs: tools/lint/lint-debt.mjs excludes these files from lint findings.",
      globs,
    },
    null,
    2,
  );
}

/** The markers of one generated block in AGENTS.md. */
export function markers(name: string): { start: string; end: string } {
  return {
    start: `<!-- ${name}:start (generated by \`pnpm gen registry-docs\`; do not edit) -->`,
    end: `<!-- ${name}:end -->`,
  };
}

/** One generated block of AGENTS.md: the text between the markers, from the checkout at `root`. */
export type Block = { name: string; render: (root: string) => string };

/** The repo map stays under this many bytes: rows are cut shorter, then fall back to the README title. */
export const REPO_MAP_BUDGET = 3584;
/** Row lengths the repo map tries, longest first. */
const SENTENCE_CUTS = [80, 60] as const;

const sorted = (): Generator[] =>
  [...GENERATORS].sort((a, b) => a.order - b.order);

function shell(c: Cmd): string {
  const env = Object.entries(c.env ?? {}).map(([k, v]) => `${k}=${v}`);
  const cwd = c.cwd ? `(cd ${c.cwd} && ` : "";
  return `${cwd}${[...env, ...c.argv].join(" ")}${c.cwd ? ")" : ""}`;
}

/** The command a person types to regenerate (or check) a family. */
export function command(g: Generator, check = false): string {
  if (g.checkOnly) return `pnpm gen ${g.id}`;
  return `pnpm gen ${g.id}${check ? " --check" : ""}`;
}

function list(globs: string[]): string {
  return globs.length === 0
    ? "none (a checker)"
    : globs.map((x) => `\`${x}\``).join(", ");
}

function mode(g: Generator): string {
  if (g.manual) return "named run only";
  if (g.via) return `runs with \`${g.via}\``;
  if (g.checkOnly) return "check only";
  return g.fast ? "default, pre-commit" : "default";
}

export function agentsTable(): string {
  const { start, end } = markers("generators");
  return [
    start,
    "",
    "`pnpm gen <family>` regenerates a family, `pnpm gen --check` checks them all. Per family:",
    "",
    ...sorted().map((g) => `- \`${g.id}\`: ${g.title}`),
    "",
    "Inputs and outputs per family: `packages/docs/src/content/docs/reference/generators.mdx`.",
    "",
    end,
  ].join("\n");
}

function readme(root: string, dir: string): string | null {
  const f = join(root, dir, "README.md");
  return existsSync(f) ? readFileSync(f, "utf8") : null;
}

const plain = (t: string): string =>
  t
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/\*\*/g, "")
    .replace(/\s+/g, " ")
    .trim();

function cut(t: string, max: number): string {
  if (t.length <= max) return t;
  const head = t.slice(0, max + 1);
  const at = head.lastIndexOf(" ");
  let s = head.slice(0, at > 0 ? at : max);
  // Never leave a code span open.
  if ((s.match(/`/g) ?? []).length % 2 === 1)
    s = s.slice(0, s.lastIndexOf("`"));
  return `${s.replace(/[,;:(—\s]+$/, "")}…`;
}

/**
 * The README's H1 and the lead clause of its first sentence: what precedes the first colon, dash
 * or semicolon is the description, the rest is detail. `line` is null when the first paragraph is
 * not a sentence (an install line ending in a colon, say).
 */
export function readmeSummary(
  text: string,
  max: number = SENTENCE_CUTS[0],
): { title: string; line: string | null } {
  const lines = text.split("\n");
  const h = lines.findIndex((l) => l.startsWith("# "));
  const title = plain(lines[h]?.slice(2) ?? "");
  const para: string[] = [];
  for (const l of lines.slice(h + 1)) {
    if (l.trim() === "") {
      if (para.length > 0) break;
      continue;
    }
    if (/^(#|\||```)/.test(l)) break;
    para.push(l);
  }
  const body = plain(para.join(" "));
  const m = /^.*?[.!?](?=\s|$)/.exec(body);
  if (!m) return { title, line: null };
  const clause = /^(.{20,}?)(?:: | — |; )/.exec(m[0]);
  return {
    title,
    line: cut(clause?.[1] ?? m[0].replace(/[.!?]$/, ""), max),
  };
}

function subdirs(root: string, dir: string): string[] {
  return readdirSync(join(root, dir), { withFileTypes: true })
    .filter((d) => d.isDirectory() && !d.name.startsWith("."))
    .map((d) => d.name)
    .sort();
}

/** The `docs/README.md` Layout lines for its top-level directories: `name/` -> description. */
function docsLayout(root: string): Map<string, string> {
  const out = new Map<string, string>();
  const text = readme(root, "docs") ?? "";
  for (const l of text.split("\n")) {
    const m = /^ {2}([a-z][\w-]*)\/\s{2,}(\S.*)$/.exec(l);
    if (m?.[1] && m[2]) out.set(m[1], m[2].trim());
  }
  return out;
}

/** The repo map: one row per workspace package, SDK and top-level directory. */
export function repoMap(root = ROOT): string {
  const dirs: string[] = [];
  for (const n of subdirs(root, "packages"))
    if (existsSync(join(root, "packages", n, "package.json")))
      dirs.push(`packages/${n}`);
  for (const n of subdirs(root, "sdks")) dirs.push(`sdks/${n}`);
  dirs.push(
    "conformance",
    "tools",
    "products",
    "actions/publish",
    "examples",
    "docs",
  );
  for (const n of subdirs(root, "docs")) dirs.push(`docs/${n}`);
  const layout = docsLayout(root);
  const shortest = SENTENCE_CUTS[1];
  // `max` null: every README row is its title.
  const rows = (max: number | null): string[] =>
    dirs.map((d) => {
      const text = readme(root, d);
      // A docs/*/ row reads its docs/README.md Layout line, written as exactly this description.
      const line = d.startsWith("docs/") ? layout.get(d.slice(5)) : undefined;
      if (line !== undefined || text === null) {
        if (line === undefined)
          throw new Error(
            `repo map: ${d}/ has no README.md and no docs/README.md Layout line`,
          );
        const link = text === null ? `${d}/` : `${d}/README.md`;
        return `- [\`${d}/\`](${link}): ${cut(line, max ?? shortest)}`;
      }
      const s = readmeSummary(text, max ?? shortest);
      return `- [\`${d}/\`](${d}/README.md): ${max === null ? s.title : (s.line ?? s.title)}`;
    });
  const wrap = (r: string[]): string => {
    const { start, end } = markers("repo-map");
    return [start, "", ...r, "", end].join("\n");
  };
  for (const max of SENTENCE_CUTS) {
    const map = wrap(rows(max));
    if (Buffer.byteLength(map) <= REPO_MAP_BUDGET) return map;
  }
  return wrap(rows(null));
}

/** The scoped and full command of a gate step, with `<base>` and `<files>` standing for the run's values. */
export function gateCommands(s: GateStep): { scoped: string; full: string } {
  const ctx: GateContext = {
    root: ".",
    mergeBase: "<base>",
    files: ["<files>"],
    existing: ["<files>"],
    full: false,
  };
  const show = (argv: string[] | null): string =>
    argv === null ? "-" : argv.join(" ");
  const scoped = show(s.argv(ctx));
  const fullCtx = { ...ctx, full: true };
  const full = show((s.argvFull ?? s.argv)(fullCtx));
  const cwd = s.cwd ? `(cd ${s.cwd} && ` : "";
  const wrap = (c: string): string => (cwd ? `${cwd}${c})` : c);
  return { scoped: wrap(scoped), full: wrap(full) };
}

/** The gate's steps as a table, from `STEPS` (tools/gate.mjs). */
export function gateTable(): string {
  const { start, end } = markers("gate");
  const rows = STEPS.map((s) => {
    const { scoped, full } = gateCommands(s);
    const when = s.fullOnly
      ? "`--full` only"
      : s.lane === null
        ? "always"
        : `lane \`${s.lane}\``;
    const narrowed = !s.fullOnly && scoped !== full;
    const flags = [
      narrowed ? "scoped to the diff" : "",
      s.heavy ? "heavy" : "",
      s.slot ? "slot" : "",
    ]
      .filter(Boolean)
      .join(", ");
    return `| ${s.n} | ${s.id} | ${when}${flags ? ` (${flags})` : ""} | \`${full}\` |`;
  });
  return [
    start,
    "",
    "| n | id | runs when | command (the `--full` form) |",
    "| --- | --- | --- | --- |",
    ...rows,
    "",
    end,
  ].join("\n");
}

/** Every generated block of AGENTS.md. A new block is one entry here and a marker pair in the file. */
export const BLOCKS: Block[] = [
  { name: "generators", render: () => agentsTable() },
  { name: "repo-map", render: (root) => repoMap(root) },
  { name: "gate", render: () => gateTable() },
];

/** Splice every block's output between its markers. A missing marker pair throws. */
export function spliceBlocks(agents: string, root = ROOT): string {
  let text = agents;
  for (const b of BLOCKS) {
    const { start, end } = markers(b.name);
    const s = text.indexOf(start);
    const e = text.indexOf(end);
    if (s < 0 || e < s)
      throw new Error(`${AGENTS_PATH} lacks the ${start} ... ${end} markers`);
    text = text.slice(0, s) + b.render(root) + text.slice(e + end.length);
  }
  return text;
}

export function pageSource(): string {
  const parts: string[] = [
    "---",
    'title: "Generators"',
    'description: "Every generator the repository runs, what each reads and writes, and the one command that regenerates or checks them all."',
    "---",
    "",
    "{/* GENERATED PAGE — do not edit. Regenerate with `pnpm gen registry-docs`.",
    "    Source of truth: tools/generators.ts; emitter: tools/gen-generators-doc.ts. */}",
    "",
    "Generated files are committed, never hand-edited. `tools/generators.ts` declares every generator once; `pnpm gen` runs them.",
    "",
    "| Command | Does |",
    "| --- | --- |",
    "| `pnpm gen` | Regenerates every default family in order. |",
    "| `pnpm gen --check` | Fails when any default family is stale. Writes nothing. CI and the green gate run this. |",
    "| `pnpm gen --changed` | Only the families whose inputs or outputs changed on this branch. Add `--check` to verify. |",
    "| `pnpm gen --fast --check` | Only the cheap families. The pre-commit hook runs this. |",
    "| `pnpm gen <family> ...` | The named families. Extra `--flag value` pairs go to a single named family. |",
    "| `pnpm gen --list` | One line per family. |",
    "",
    "A new generator is one entry in `tools/generators.ts`. A test fails when a file carries a GENERATED banner that no entry claims.",
    "",
    "## Families",
    "",
  ];
  for (const g of sorted()) {
    parts.push(`### ${g.id}`, "", g.title + ".", "");
    parts.push(`- Run: ${mode(g)}.`);
    if (!g.checkOnly) parts.push(`- Regenerate: \`${command(g)}\`.`);
    parts.push(`- Check: \`${command(g, true)}\`.`);
    const steps = g.manual && !g.write ? [] : (g.write ?? []);
    if (steps.length > 0)
      parts.push(
        `- Underlying: ${steps.map((s) => `\`${shell(s)}\``).join(", then ")}.`,
      );
    if (g.manual) parts.push(`- Why not default: ${g.manual}.`);
    if (g.needsBuild) parts.push("- Needs `pnpm build` first.");
    parts.push(
      `- Reads: ${list(g.inputs)}.`,
      `- Writes: ${list(g.outputs)}.`,
      "",
    );
  }
  return parts.join("\n");
}

async function fmt(text: string, file: string): Promise<string> {
  const cfg = (await prettier.resolveConfig(join(ROOT, file))) ?? {};
  return prettier.format(text, { ...cfg, filepath: join(ROOT, file) });
}

export async function render(root = ROOT): Promise<Map<string, string>> {
  const out = new Map<string, string>();
  // Like the other reference pages, written as-is: prettier would rewrite the MDX comment.
  out.set(PAGE_PATH, pageSource());
  const agents = readFileSync(join(root, AGENTS_PATH), "utf8");
  const next = spliceBlocks(agents, root);
  out.set(AGENTS_PATH, await fmt(next, AGENTS_PATH));
  out.set(SNAPSHOT_PATH, await fmt(snapshotSource(), SNAPSHOT_PATH));
  return out;
}

async function main(): Promise<number> {
  const check = process.argv.includes("--check");
  const files = await render();
  let stale = 0;
  for (const [path, text] of files) {
    let current = "";
    try {
      current = readFileSync(join(ROOT, path), "utf8");
    } catch {
      /* missing: stale */
    }
    if (current === text) continue;
    stale++;
    if (check) console.error(`stale: ${path}`);
    else {
      writeFileSync(join(ROOT, path), text);
      console.log(`wrote ${path}`);
    }
  }
  if (check && stale > 0) {
    console.error(
      "gen registry-docs --check: run `pnpm gen registry-docs` and commit the result",
    );
    return 1;
  }
  return 0;
}

const isMain =
  process.argv[1] !== undefined &&
  fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) process.exit(await main());

// Writes the route ledger table of docs/design/ADMIN.md §2.8 from packages/admin/src/console/
// routeLedger.ts (the one map of 0.9 page addresses to 1.0 pages) and nav.ts (the 1.0 labels and paths).
// The prose of the section is hand-written; the block between the markers is output.
//
//   pnpm gen route-ledger            # write the block
//   pnpm gen route-ledger --check    # exit 1 when the block is stale

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";
import { pageOf, sectionOf } from "../packages/admin/src/console/nav.js";
import {
  ROUTE_LEDGER,
  type LedgerRow,
} from "../packages/admin/src/console/routeLedger.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const FILE = join(ROOT, "docs/design/ADMIN.md");
export const START =
  "<!-- route-ledger:start (GENERATED by `pnpm gen route-ledger` from routeLedger.ts; do not edit) -->";
export const END = "<!-- route-ledger:end -->";

const address = (scope: string, path: string): string =>
  scope === "product" ? `#/p/<slug>/${path}` : `#/${path}`;

function now(row: LedgerRow): string {
  if (row.fate === "deleted") return `deleted (${row.by})`;
  const id = row.fate === "live" ? row.id : row.to!;
  const page = pageOf(id as never);
  const section = sectionOf(id as never);
  const label = section ? `${section.label} → ${page.label}` : page.label;
  return `${label} (\`${address(row.scope, page.path).replace(/\/$/, "")}\`)`;
}

function status(row: LedgerRow): string {
  if (row.fate === "live") return "live";
  return `${row.fate} (${row.by})`;
}

export function renderBlock(): string {
  const lines = [
    START,
    "",
    "| 0.9 page | 0.9 address | 1.0 home | Status |",
    "| --- | --- | --- | --- |",
    ...ROUTE_LEDGER.map(
      (row) =>
        `| \`${row.id}\` | \`${address(row.scope, row.from).replace(/\/$/, "")}\` | ${now(row)} | ${status(row)} |`,
    ),
    "",
    END,
  ];
  return lines.join("\n");
}

async function main(): Promise<void> {
  const check = process.argv.includes("--check");
  const current = readFileSync(FILE, "utf8");
  const a = current.indexOf(START);
  const b = current.indexOf(END);
  if (a === -1 || b === -1) {
    console.error(`route-ledger: markers missing in docs/design/ADMIN.md`);
    process.exit(1);
  }
  const next =
    current.slice(0, a) + renderBlock() + current.slice(b + END.length);
  const formatted = await prettier.format(next, {
    ...((await prettier.resolveConfig(FILE)) ?? {}),
    filepath: FILE,
  });
  if (formatted === current) return;
  if (check) {
    console.error(
      "route-ledger: docs/design/ADMIN.md §2.8 is stale; run `pnpm gen route-ledger`",
    );
    process.exit(1);
  }
  writeFileSync(FILE, formatted);
  console.log("route-ledger: wrote docs/design/ADMIN.md");
}

void main();

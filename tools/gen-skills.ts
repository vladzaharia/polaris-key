// The agent-kit skills generator family (AX-07.4).
//
//   pnpm gen skills            # (re)write the generated skill references
//   pnpm gen skills --check    # regenerate in memory; exit 1 if any differs
//
// Each output is a `references/*.md` file under packages/agent-kit/skills/<skill>/. Today one:
// authoring-pkey-manifests/references/validation-codes.md, the `.pkey/` validator's error and
// warning codes. It reads the same extractor as the docs page (`validationCodeRows()` in
// packages/docs/scripts/gen-reference.mjs), so the two cannot disagree. AX-09 and AX-12 add their
// references as more entries of `renderAll`.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";
// @ts-expect-error -- plain .mjs without declarations
import { validationCodeRows } from "../packages/docs/scripts/gen-reference.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

export const VALIDATION_CODES_PATH =
  "packages/agent-kit/skills/authoring-pkey-manifests/references/validation-codes.md";

const BANNER =
  "<!-- GENERATED by `pnpm gen skills` from packages/shared-manifest/src; do not edit. -->";

type Row = [string, string, string, string, string];
type DescriptorRow = [string, string, string];

/**
 * A skill reference must pass `pnpm skills:check`: no programme ids (rule 5) and no bare key
 * generation command outside a handoff fence (rule 7). The validator's messages carry both
 * today, so they are reworded here and nowhere else.
 */
const forSkill = (s: string): string =>
  s
    .replace(/\s*\(P\d+[a-z]*-\d+[a-z0-9.]*\)/g, "")
    .replace(/`pkey release keys generate`/g, "the release-key generator");

const cell = (s: string): string =>
  forSkill(s).replace(/\|/g, "\\|").replace(/\n/g, " ");
const code = (s: string): string => `\`${s}\``;

function table(headers: string[], rows: string[][]): string {
  return [
    `| ${headers.join(" | ")} |`,
    `| ${headers.map(() => "---").join(" | ")} |`,
    ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`),
  ].join("\n");
}

const DOCUMENTS = ["product", "schema", "release", "distribution"] as const;

export function renderValidationCodes(): string {
  const { rows, descriptor } = validationCodeRows() as {
    rows: Row[];
    descriptor: DescriptorRow[];
  };
  const sections: string[] = [];
  const toc: string[] = [];
  for (const doc of DOCUMENTS) {
    const own = rows.filter((r) => r[2] === doc);
    if (own.length === 0) continue;
    toc.push(`- [\`${doc}\`](#${doc}-codes): ${own.length} codes`);
    sections.push(
      `## ${doc} codes\n\n` +
        table(
          ["Code", "Severity", "Path", "Message"],
          own.map((r) => [code(r[0]), r[1], code(r[3]), r[4]]),
        ),
    );
  }
  toc.push(
    `- [Release descriptor](#release-descriptor-codes): ${descriptor.length} codes`,
  );
  sections.push(
    `## Release descriptor codes\n\n` +
      table(
        ["Code", "Path", "Message"],
        descriptor.map((r) => [code(r[0]), code(r[1]), r[2]]),
      ),
  );
  return [
    BANNER,
    "",
    "# Manifest validation codes",
    "",
    "Every error and warning `pkey validate` can emit, with its JSON-pointer path and message. `${…}` in a path or message is a per-instance value.",
    "",
    "Contents:",
    "",
    ...toc,
    "",
    sections.join("\n\n"),
    "",
  ].join("\n");
}

async function format(path: string, text: string): Promise<string> {
  const filepath = join(ROOT, path);
  const options = (await prettier.resolveConfig(filepath)) ?? {};
  // Prettier's table pass is not idempotent on messages with `[]` or `*`; run it to a fixpoint so
  // the committed file is what `prettier --check` accepts.
  let out = text;
  for (let i = 0; i < 4; i++) {
    const next = await prettier.format(out, { ...options, filepath });
    if (next === out) break;
    out = next;
  }
  return out;
}

/** Every generated skill reference: repo-relative path to content. */
export async function renderAll(): Promise<Map<string, string>> {
  return new Map([
    [
      VALIDATION_CODES_PATH,
      await format(VALIDATION_CODES_PATH, renderValidationCodes()),
    ],
  ]);
}

/** Write (or, with `check`, compare) the outputs. Returns the stale paths. */
export async function run(opts: { check: boolean }): Promise<string[]> {
  const stale: string[] = [];
  for (const [path, content] of await renderAll()) {
    const abs = join(ROOT, path);
    if (existsSync(abs) && readFileSync(abs, "utf8") === content) continue;
    stale.push(path);
    if (opts.check) continue;
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, content);
  }
  return stale;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const stale = await run({ check });
  for (const path of stale)
    console[check ? "error" : "log"](
      check ? `stale: ${path}, run \`pnpm gen skills\`` : `wrote ${path}`,
    );
  if (check && stale.length > 0) process.exit(1);
}

/** Whether `glob` can select a path below `dir`. */
function globTouchesDirectory(glob: string, dir: string): boolean {
  const pattern = (glob.endsWith("/") ? `${glob}**` : glob)
    .split("/")
    .filter(Boolean);
  const target = dir.split("/").filter(Boolean);

  const visit = (patternIndex: number, targetIndex: number): boolean => {
    if (targetIndex === target.length) return patternIndex < pattern.length;
    if (patternIndex === pattern.length) return false;

    const part = pattern[patternIndex] as string;
    if (part === "**")
      return (
        visit(patternIndex + 1, targetIndex) ||
        visit(patternIndex, targetIndex + 1)
      );

    return (
      globToRegExp(part).test(target[targetIndex] as string) &&
      visit(patternIndex + 1, targetIndex + 1)
    );
  };

  return visit(0, 0);
}

type Relation = "reads" | "writes" | "reads and writes";

/** The registry families whose inputs or outputs sit under `dir`. */
export function familiesFor(
  dir: string,
): { family: Generator; relation: Relation }[] {
  const rows: { family: Generator; relation: Relation }[] = [];
  for (const family of [...GENERATORS].sort((a, b) => a.order - b.order)) {
    const reads = family.inputs.some((g) => globTouchesDirectory(g, dir));
    const writes = family.outputs.some((g) => globTouchesDirectory(g, dir));
    if (reads || writes)
      rows.push({
        family,
        relation:
          reads && writes ? "reads and writes" : writes ? "writes" : "reads",
      });
  }
  return rows;
}

function readJson(path: string): {
  name?: string;
  scripts?: Record<string, string>;
} {
  return JSON.parse(readFileSync(join(ROOT, path), "utf8"));
}

/** The generated block for one README, without the markers. */
export function renderBlock(target: Target): string {
  const rows: [string, string][] = [];
  for (const p of target.packages) {
    const pkg = readJson(`${p.dir}/package.json`);
    if (!pkg.name) throw new Error(`${p.dir}/package.json has no name`);
    for (const [script, does] of p.scripts) {
      if (!pkg.scripts?.[script])
        throw new Error(`${p.dir}/package.json has no "${script}" script`);
      rows.push([`pnpm --filter ${pkg.name} ${script}`, does]);
    }
    if (p.oneTest)
      rows.push([
        `pnpm --filter ${pkg.name} exec vitest run <test file>`,
        "Run one test file (the path is relative to the package).",
      ]);
  }
  const root = readJson("package.json");
  for (const [script, does] of target.rootScripts ?? []) {
    if (!root.scripts?.[script])
      throw new Error(`package.json has no "${script}" script`);
    rows.push([`pnpm ${script}`, does]);
  }
  const up = posix.relative(target.dir, "AGENTS.md");
  const out: string[] = [
    START,
    "",
    `Run the JavaScript commands under Node 22 (see [\`AGENTS.md\`](${up})).`,
  ];
  if (rows.length > 0) {
    out.push("", "| Command | Does |", "| --- | --- |");
    for (const [cmd, does] of rows) out.push(`| \`${cmd}\` | ${does} |`);
  }
  const families = familiesFor(target.dir);
  if (families.length > 0) {
    out.push(
      "",
      "Generator families that read or write files here (a family regenerates with `pnpm gen <family>`, and `pnpm gen --check` is the drift gate):",
      "",
      "| Family | Here it | Run |",
      "| --- | --- | --- |",
    );
    for (const { family, relation } of families) {
      const run = family.manual
        ? `\`pnpm gen ${family.id}\` (named run only)`
        : family.via
          ? `runs with \`${family.via}\``
          : `\`pnpm gen ${family.id}\``;
      out.push(`| \`${family.id}\` | ${relation} | ${run} |`);
    }
  }
  out.push("", END);
  return out.join("\n");
}

/** `text` with its marker block replaced by `block`. */
export function applyBlock(text: string, block: string, file: string): string {
  const s = text.indexOf(START);
  const e = text.indexOf(END);
  if (s < 0 || e < s)
    throw new Error(`${file} lacks the work-on-it markers (${START} … ${END})`);
  return text.slice(0, s) + block + text.slice(e + END.length);
}

async function format(text: string, file: string): Promise<string> {
  const cfg = (await prettier.resolveConfig(join(ROOT, file))) ?? {};
  return prettier.format(text, { ...cfg, filepath: join(ROOT, file) });
}

export async function render(): Promise<Map<string, string>> {
  const out = new Map<string, string>();
  for (const target of TARGETS) {
    const file = `${target.dir}/README.md`;
    const text = readFileSync(join(ROOT, file), "utf8");
    out.set(
      file,
      await format(applyBlock(text, renderBlock(target), file), file),
    );
  }
  return out;
}

async function main(): Promise<number> {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [file, text] of await render()) {
    if (readFileSync(join(ROOT, file), "utf8") === text) continue;
    stale++;
    if (check) console.error(`stale: ${file}`);
    else {
      writeFileSync(join(ROOT, file), text);
      console.log(`wrote ${file}`);
    }
  }
  if (check && stale > 0) {
    console.error(
      "gen readme-work --check: run `pnpm gen readme-work` and commit the result",
    );
    return 1;
  }
  return 0;
}

const isMain =
  process.argv[1] !== undefined &&
  fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) process.exit(await main());

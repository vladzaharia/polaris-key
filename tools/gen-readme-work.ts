// Fills the "Work on it" section of every internal README from what the repository declares: the
// scripts in each package.json and the generator registry (tools/generators.ts). The README prose
// never types a command; the block between the markers is output.
//
//   pnpm gen readme-work            # write every README's block
//   pnpm gen readme-work --check    # exit 1 when any block is stale


interface PackageTarget {
  /** The workspace package's directory; its name and scripts come from its package.json. */
  dir: string;
  /** Scripts to list, each with what it does. A script a package.json lacks is an error. */
  scripts: [script: string, does: string][];
  /** Whether a single test file runs with `vitest run <file>` in this package. */
  oneTest?: boolean;
}

interface Target {
  /** The directory whose README is filled. */
  dir: string;
  packages: PackageTarget[];
  /** Scripts of the root package.json that this directory is worked on with. */
  rootScripts?: [script: string, does: string][];
}


import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { VALIDATION_CODES_PATH, renderAll, run } from "./gen-skills.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

describe("gen-skills", () => {
  it("is current on disk", async () => {
    expect(await run({ check: true })).toEqual([]);
  });

  it("opens with the GENERATED banner", async () => {
    const text = (await renderAll()).get(VALIDATION_CODES_PATH)!;
    expect(text.startsWith("<!-- GENERATED by `pnpm gen skills`")).toBe(true);
    expect(text.split("\n")[0]).toBe(
      "<!-- GENERATED by `pnpm gen skills` from packages/shared-manifest/src; do not edit. -->",
    );
  });

  it("lists every code of reference/validation-codes.mdx", async () => {
    const text = (await renderAll()).get(VALIDATION_CODES_PATH)!;
    const page = readFileSync(
      join(
        ROOT,
        "packages/docs/src/content/docs/reference/validation-codes.mdx",
      ),
      "utf8",
    );
    const codes = [...page.matchAll(/^\| `([a-z0-9_]+)` \|/gm)].map(
      (m) => m[1],
    );
    expect(codes.length).toBeGreaterThan(200);
    for (const c of codes) expect(text, c).toContain(`\`${c}\``);
  });

  it("opens with a contents list within the first 15 lines", async () => {
    const lines = (await renderAll()).get(VALIDATION_CODES_PATH)!.split("\n");
    expect(lines.slice(0, 15).some((l) => /\bcontents\b/i.test(l))).toBe(true);
  });
});
